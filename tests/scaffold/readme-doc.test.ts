import { expect, test, describe } from 'bun:test';
import { rm, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { generate } from '../../src/scaffold/generator';
import type { ScaffoldConfig } from '../../src/scaffold/config';

const TEMPLATE_DIR = join(import.meta.dir, '../../template');

const OPTIONAL_LAYERS = ['src/lib/validation/', 'src/routes/', 'src/services/', 'src/repositories/'] as const;

const SHARED_MARKERS = [
  '--console-panel',
  '--migrations',
  'src/panels/',
  'migrations/',
  'Optional author-added layers',
  ...OPTIONAL_LAYERS,
] as const;

function makeConfig(overrides: Partial<ScaffoldConfig> = {}): ScaffoldConfig {
  return {
    pluginId: 'test-plugin',
    provides: 'generic',
    consolePanel: false,
    migrations: false,
    ...overrides,
  };
}

async function generateDocs(
  overrides: Partial<ScaffoldConfig> = {},
): Promise<{ readme: string; agents: string }> {
  const suffix = `${Date.now()}-${Math.random().toString(36).slice(2)}`;
  const out = join(tmpdir(), `readme-doc-${suffix}`);
  try {
    await generate(makeConfig(overrides), out, TEMPLATE_DIR);
    return {
      readme: await readFile(join(out, 'README.md'), 'utf-8'),
      agents: await readFile(join(out, 'AGENTS.md'), 'utf-8'),
    };
  } finally {
    await rm(out, { recursive: true, force: true });
  }
}

describe('README.md doc currency', () => {
  test('documents src/panels/ and the --console-panel variant', async () => {
    const { readme } = await generateDocs();
    expect(readme).toContain('src/panels/');
    expect(readme).toContain('--console-panel');
  });

  test('documents migrations/ and the --migrations flag', async () => {
    const { readme } = await generateDocs();
    expect(readme).toContain('migrations/');
    expect(readme).toContain('--migrations');
  });

  test('marks optional author-added layers as not generated', async () => {
    const { readme } = await generateDocs();
    expect(readme).toContain('Optional author-added layers (not generated by the scaffold)');
    for (const layer of OPTIONAL_LAYERS) {
      expect(readme).toContain(layer);
    }
  });

  test('does not present optional layers as generated tree entries', async () => {
    const { readme } = await generateDocs();
    expect(readme).not.toMatch(/├──\s+(lib\/validation|routes|services|repositories)\//);
    expect(readme).not.toMatch(/└──\s+(lib\/validation|routes|services|repositories)\//);
  });

  test('interpolates the plugin id', async () => {
    const { readme } = await generateDocs();
    expect(readme).toContain('test-plugin');
    expect(readme).not.toContain('{{PLUGIN_ID}}');
  });
});

describe('README.md ↔ AGENTS.md parity', () => {
  test('both docs carry the shared structure markers', async () => {
    const { readme, agents } = await generateDocs();
    for (const marker of SHARED_MARKERS) {
      expect(readme).toContain(marker);
      expect(agents).toContain(marker);
    }
  });
});
